// @vitest-environment happy-dom
import "fake-indexeddb/auto";
import { loadWorkspace } from "@open-arch/core";
import { strFromU8, unzipSync } from "fflate";
import { act, createElement } from "react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { App } from "../src/App.js";
import { folderList } from "../src/folders.js";
import { exampleHost } from "../src/hosts.js";
import { SKILL_TARGETS } from "../src/skill.js";
import { button, click, mount, type } from "./dom.js";
import { agentsInFolder, FakeFolder } from "./fakeFolder.js";

const until = async (done: () => boolean) => {
  for (let i = 0; i < 200 && !done(); i++) await act(() => new Promise((resolve) => setTimeout(resolve, 5)));
};

afterEach(() => {
  vi.restoreAllMocks();
});

describe("Export zip", () => {
  it("downloads the open example with its docs and the agent skill", async () => {
    const blobs: Blob[] = [];
    vi.spyOn(URL, "createObjectURL").mockImplementation((blob) => (blobs.push(blob as Blob), "blob:zip"));
    vi.spyOn(URL, "revokeObjectURL").mockImplementation(() => {});
    const names: string[] = [];
    vi.spyOn(HTMLAnchorElement.prototype, "click").mockImplementation(function (this: HTMLAnchorElement) {
      names.push(this.download);
    });
    const host = mount(createElement(App, {}));
    await until(() => !!host.textContent?.includes("Try the example"));
    await click(button(host, "Try the example"));
    await until(() => !!host.querySelector(".ws-name"));
    await click(button(host, "Export zip"));

    expect(names).toEqual(["shop.zip"]);
    const files = unzipSync(new Uint8Array(await blobs[0]!.arrayBuffer()));
    expect(strFromU8(files["shop/shop.openarch"]!)).toBe(await exampleHost().load());
    expect(Object.keys(files)).toContain("shop/docs/README.md");
    for (const target of SKILL_TARGETS) expect(Object.keys(files)).toContain(`shop/${target}/SKILL.md`);
  });
});

describe("Export to folder", () => {
  /** The app with the example open, and a folder for the picker to give. */
  async function exampleOpen(root: FakeFolder | null) {
    Object.assign(window, { showDirectoryPicker: async () => root });
    const host = mount(createElement(App, {}));
    await until(() => !!host.textContent?.includes("Try the example"));
    await click(button(host, "Try the example"));
    await until(() => !!host.querySelector(".ws-name"));
    return host;
  }
  const message = (host: HTMLElement) => host.querySelector('[role="alert"], [role="status"]')?.textContent ?? host.textContent ?? "";

  afterEach(() => {
    delete (window as { showDirectoryPicker?: unknown }).showDirectoryPicker;
  });

  it("exports the open example to a folder the user picks, lists the folder, and marks the example saved", async () => {
    const root = new FakeFolder("repo");
    const host = await exampleOpen(root);
    // An edit, so the example isn't saved.
    await click(host.querySelector(".ws-name")!);
    const name = [...host.querySelectorAll<HTMLInputElement>(".properties input")].find((input) => input.getAttribute("aria-label") === "Name")!;
    await type(name, "Shop 2");
    await act(async () => void name.dispatchEvent(new FocusEvent("focusout", { bubbles: true })));
    await until(() => host.querySelector(".storage")?.textContent === "Not saved");
    await click(button(host, "Export to folder…"));
    await until(() => !!host.textContent?.includes("Exported shop.openarch"));
    expect(host.textContent).toContain("Exported shop.openarch to repo, as a workspace there, with its docs, the agent skill and AGENTS.md. Open it from Folders on the start page to keep working on it there.");
    expect(loadWorkspace(root.files()["shop.openarch"]!).doc.name).toBe("Shop 2");
    expect(Object.keys(root.files())).toContain("AGENTS.md");
    expect(host.querySelector(".storage")?.textContent).not.toBe("Not saved");
    expect((await folderList.list()).some((record) => record.root.name === "repo" && record.path === "shop.openarch")).toBe(true);
  });

  it("says what went wrong beside writing the file, and what was left alone", async () => {
    const root = new FakeFolder("repo");
    root.refuse.add(".claude");
    root.put("docs/README.md", "# Mine");
    const host = await exampleOpen(root);
    await click(button(host, "Export to folder…"));
    await until(() => !!host.textContent?.includes("Exported shop.openarch"));
    expect(message(host)).toContain(
      "Exported shop.openarch to repo, as a workspace there, with its docs, the agent skill and AGENTS.md. The agent skill in .agents/skills/open-arch/ and .claude/skills/open-arch/ wasn't updated: Not allowed. Left alone in the docs (not generated by open-arch, or generated for another workspace beside it): README.md.",
    );
  });

  it("says when AGENTS.md names another workspace there, and when the folder couldn't be listed", async () => {
    const root = new FakeFolder("repo");
    root.put("b.openarch", JSON.stringify({ openarch: 18, name: "B", elements: {}, views: {} }));
    root.put("AGENTS.md", agentsInFolder("b.openarch")["AGENTS.md"]!);
    vi.spyOn(folderList, "add").mockRejectedValue(new Error("No storage."));
    const host = await exampleOpen(root);
    await click(button(host, "Export to folder…"));
    await until(() => !!host.textContent?.includes("Exported shop.openarch"));
    expect(message(host)).toContain(
      "Exported shop.openarch to repo, as a workspace there, with its docs, the agent skill and AGENTS.md. AGENTS.md's open-arch section names b.openarch, another workspace there, so it was left as it is. It couldn't be listed under Folders on the start page: open it with Open folder… to keep working on it there.",
    );
  });

  it("isn't offered in the desktop app, which keeps its files where they are", async () => {
    Object.assign(window, { showDirectoryPicker: async () => new FakeFolder("repo") });
    const text = await exampleHost().load();
    const bridge = {
      lastFile: async () => ({ path: "/repo/shop.openarch", name: "shop.openarch" }),
      load: async () => text,
      save: async () => ({ docs: null }),
      watch: () => () => {},
    };
    Object.assign(window, { openArchDesktop: bridge });
    try {
      const host = mount(createElement(App, {}));
      await until(() => !!host.querySelector(".ws-name"));
      expect([...host.querySelectorAll("button")].some((b) => b.textContent?.trim() === "Export to folder…")).toBe(false);
    } finally {
      delete (window as { openArchDesktop?: unknown }).openArchDesktop;
    }
  });

  it("says why nothing was exported to a folder that has the file already", async () => {
    const root = new FakeFolder("repo");
    root.put("shop.openarch", "{}");
    const host = await exampleOpen(root);
    await click(button(host, "Export to folder…"));
    await until(() => !!host.textContent?.includes("nothing was exported"));
    expect(host.textContent).toContain("repo has a file or folder named shop.openarch already, so nothing was exported. Choose another folder, or open that one with Open folder.");
    expect(root.files()).toEqual({ "shop.openarch": "{}" });
  });

  it("is in the menu on a narrow screen", async () => {
    const real = window.matchMedia;
    window.matchMedia = ((query: string) => ({ matches: true, media: query, addEventListener() {}, removeEventListener() {} })) as unknown as typeof window.matchMedia;
    try {
      const root = new FakeFolder("repo");
      const host = await exampleOpen(root);
      await click(host.querySelector('button[aria-label="More"]')!);
      const item = [...document.querySelectorAll<HTMLElement>('.context-menu [role="menuitem"]')].find((i) => i.textContent?.trim() === "Export to folder…");
      expect(item).toBeDefined();
      await click(item!);
      await until(() => !!root.files()["shop.openarch"]);
      expect(root.files()["shop.openarch"]).toBeDefined();
    } finally {
      window.matchMedia = real;
    }
  });

  it("isn't offered where the browser can't write to a folder", async () => {
    const host = mount(createElement(App, {}));
    await until(() => !!host.textContent?.includes("Try the example"));
    await click(button(host, "Try the example"));
    await until(() => !!host.querySelector(".ws-name"));
    expect([...host.querySelectorAll("button")].some((b) => b.textContent?.trim() === "Export to folder…")).toBe(false);
  });
});
