/**
 * Human-readable docs generated from a workspace: an index, one page per
 * element and one per view with its Mermaid diagram. They're output only:
 * every page says so, and tools rewrite them freely.
 */
import { nodeKindLabel, renderMermaid, shapesInReadingOrder, transitionLabel } from "./mermaid.js";
import { kindLabel, tagEntries, tagText } from "./model.js";
import { computeAllViews, describeElement, modelTree, type TreeNode } from "./query.js";
import { shapeName } from "./views.js";
import {
  BLOCK_KIND_LABELS,
  CARD_KIND_LABELS,
  CARDINALITY_LABELS,
  endShape,
  endSide,
  SCREEN_DEVICE_LABELS,
  SHAPE_KIND_LABELS,
  SHAPE_LABELS,
  WIDGET_KIND_LABELS,
  type ArchElement,
  type Arrow,
  type Lane,
  type Relationship,
  type RelationshipKind,
  type Sticky,
  type ViewDef,
  type Widget,
} from "./types.js";
import type { Workspace } from "./workspace.js";

export interface ExportedFile {
  /** Relative to the docs folder, with `/` separators. */
  path: string;
  content: string;
}

/**
 * The folders in the docs folder that exportDocs writes pages into, beside README.md at its top.
 * Stale pages are only looked for there, so a docs folder that's also the workspace file's own
 * folder, or a repository's top, never has anything else in it looked through or deleted.
 */
export const DOCS_PAGE_FOLDERS = ["elements", "views"];

/** Every generated page starts with this, which is how tools know they may overwrite or delete it. */
export const GENERATED_MARKER = "<!-- Generated by open-arch";

function banner(source: string): string {
  return `${GENERATED_MARKER} from ${source}. Don't edit: change the model in the designer or with the open-arch CLI, and this page is rewritten. -->`;
}

/**
 * The file a generated page says it was generated from, or null for a page open-arch didn't
 * generate, and "" for an older page that names no file. Tools use it to leave alone pages
 * generated from another workspace whose file is in the same folder as the one they're saving.
 */
export function generatedFrom(text: string): string | null {
  if (!text.startsWith(GENERATED_MARKER)) return null;
  const match = /^<!-- Generated by open-arch from (.*?)\. Don't edit:/.exec(text);
  return match ? match[1]! : "";
}

/** Text safe inside a markdown table cell. */
function cell(text: string | undefined): string {
  return (text ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function link(e: ArchElement, from: "root" | "elements" | "views"): string {
  const href = from === "elements" ? `${e.id}.md` : from === "views" ? `../elements/${e.id}.md` : `elements/${e.id}.md`;
  return `[${e.name}](${href})`;
}

/**
 * What a sticky note is on, to start its quote: "On [Cache](…): ", or "On [Web App](…) →
 * [Orders DB](…): ", or on a flowchart view, the block's text, 'On "Pack the order": '. Nothing
 * for a note on nothing.
 */
function stickyOn(ws: Workspace, view: ViewDef, s: Sticky): string {
  const on = s.on;
  if (!on) return "";
  if ("block" in on) {
    const block = view.blocks.find((b) => b.id === on.block);
    // On one line, as the table of blocks has it.
    const text = block?.text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean).join(" / ");
    return `On "${text ?? on.block}": `;
  }
  const name = (id: string) => {
    const e = ws.elements.get(id);
    return e ? link(e, "views") : id;
  };
  if ("element" in on) return `On ${name(on.element)}: `;
  return `On ${name(on.from)} → ${name(on.to)}${on.kind === "association" ? "" : ` (${on.kind})`}: `;
}

/** A relationship's description for a table, saying what kind it is, when it isn't an association, and when it goes both ways. */
function described(r: { description?: string; bidirectional: boolean; kind: RelationshipKind }): string {
  return [r.kind === "association" ? "" : `(${r.kind})`, cell(r.description), r.bidirectional ? "(both ways)" : ""].filter(Boolean).join(" ");
}

/** Relationships to or from an element, with a Tags column when any of them has tags. */
function relTable(ws: Workspace, rows: { other: string; rel: Relationship }[]): string[] {
  const tagged = rows.some(({ rel }) => Object.keys(rel.tags).length > 0);
  const head = tagged ? ["| Element | Description | Technology | Tags |", "|---|---|---|---|"] : ["| Element | Description | Technology |", "|---|---|---|"];
  return [
    ...head,
    ...rows.map(({ other, rel }) => {
      const target = ws.elements.get(other);
      return `| ${target ? link(target, "elements") : cell(other)} | ${described(rel)} | ${cell(rel.technology)} |${tagged ? ` ${cell(tagText(rel.tags))} |` : ""}`;
    }),
  ];
}

/**
 * The notes of these relationships, for under the table that lists them: each under a
 * heading that names it, as the table's rows can't hold markdown. Those without notes are left out.
 */
function relNotes(ws: Workspace, rows: { from: string; rel: Relationship }[]): string[] {
  const name = (id: string) => ws.elements.get(id)?.name ?? id;
  return rows.flatMap(({ from, rel }) => {
    if (!rel.notes) return [];
    const description = rel.description ? `: ${rel.description.replace(/\s*\r?\n\s*/g, " ")}` : "";
    return ["", `### ${name(from)} ${rel.bidirectional ? "↔" : "→"} ${name(rel.to)}${description}`, "", rel.notes];
  });
}

/**
 * The docs for a workspace. `source` names the .openarch file in the banner.
 * Paths: README.md, elements/<id>.md, views/<id>.md.
 */
export function exportDocs(ws: Workspace, source: string): ExportedFile[] {
  const top = banner(source);
  const views = computeAllViews(ws);
  const files: ExportedFile[] = [];

  // Index
  const tree: string[] = [];
  const walk = (node: TreeNode, depth: number) => {
    const e = node.element;
    tree.push(`${"  ".repeat(depth)}- ${link(e, "root")} (${kindLabel(e).toLowerCase()}${e.technology ? `, ${e.technology}` : ""})${e.description ? ` – ${e.description}` : ""}`);
    node.children.forEach((c) => walk(c, depth + 1));
  };
  modelTree(ws).forEach((n) => walk(n, 0));
  files.push({
    path: "README.md",
    content: [
      top,
      "",
      `# ${ws.doc.name}`,
      ...(ws.doc.description ? ["", ws.doc.description] : []),
      "",
      "## Views",
      "",
      ...(views.length ? views.map((cv) => `- [${cv.view.title}](views/${cv.view.id}.md)${cv.view.description ? ` – ${cv.view.description}` : ""}`) : ["No views yet."]),
      "",
      "## Model",
      "",
      ...(tree.length ? tree : ["No elements yet."]),
      "",
    ].join("\n"),
  });

  // Views
  for (const cv of views) {
    const v = cv.view;
    const scope = v.scope ? ws.elements.get(v.scope) : undefined;
    const lines = [top, "", `# ${v.title}`, "", `${v.level[0]!.toUpperCase()}${v.level.slice(1)} view${scope ? ` of ${link(scope, "views")}` : ""}.`];
    if (v.description) lines.push("", v.description);
    if (v.notes) lines.push("", v.notes);
    lines.push("", "```mermaid", renderMermaid(cv), "```");
    // The diagram's sticky notes, as quotes in reading order, each starting with what it's on,
    // with the note's own notes after its text, in the same quote.
    if (v.stickies.length) {
      const quote = (text: string, first = "") => text.split(/\r?\n/).map((l, i) => `> ${i === 0 ? first : ""}${l}`.trimEnd());
      lines.push("", "## Sticky notes", ...v.stickies.flatMap((s) => ["", ...quote(s.text, stickyOn(ws, v, s)), ...(s.notes ? [">", ...quote(s.notes)] : [])]));
    }
    if (v.level === "state") {
      const name = (id: string) => cell(v.states.find((s) => s.id === id)?.name ?? id);
      lines.push("", "## States", "");
      if (v.states.length) {
        lines.push("| State | Description |", "|---|---|");
        for (const s of v.states) {
          const marks = [s.id === v.initial ? "starts here" : "", s.final ? "can end here" : ""].filter(Boolean).join(", ");
          lines.push(`| ${cell(s.name)}${marks ? ` (${marks})` : ""} | ${cell(s.description)} |`);
        }
      } else lines.push("None yet.");
      if (v.transitions.length) {
        lines.push("", "## Transitions", "", "| # | From | To | Event [guard] / action |", "|---|---|---|---|");
        for (const t of v.transitions) lines.push(`| ${t.number} | ${name(t.from)} | ${name(t.to)} | ${cell(transitionLabel(t))} |`);
      }
      lines.push("", `[All views and elements](../README.md)`, "");
      files.push({ path: `views/${v.id}.md`, content: lines.join("\n") });
      continue;
    }
    if (cv.deployment) {
      const d = cv.deployment;
      const nodeName = (id: string) => cell(d.nodes.find((n) => n.id === id)?.name ?? id);
      const elementLink = (id: string) => {
        const e = ws.elements.get(id);
        return e ? link(e, "views") : cell(id);
      };
      lines.push("", "## Nodes", "");
      if (d.nodes.length) {
        lines.push("| Node | Kind | Inside | Technology | Copies | Runs | Description |", "|---|---|---|---|---|---|---|");
        for (const n of d.nodes) {
          const runs = d.instances.filter((i) => i.node === n.id).map((i) => link(i.element, "views"));
          lines.push(`| ${cell(n.name)} | ${nodeKindLabel(n)} | ${n.parent ? nodeName(n.parent) : ""} | ${cell(n.technology)} | ${n.instances} | ${runs.join(", ")} | ${cell(n.description)} |`);
        }
      } else lines.push("None yet.");
      if (cv.edges.length) {
        lines.push("", "## Relationships", "", "| From | To | Description | Technology |", "|---|---|---|---|");
        for (const e of cv.edges) lines.push(`| ${elementLink(e.from)} | ${elementLink(e.to)} | ${described(e)} | ${cell(e.technology)} |`);
        lines.push(...relNotes(ws, cv.edges.flatMap((e) => e.sources.map(({ element, index }) => ({ from: element, rel: ws.elements.get(element)!.uses[index]! })))));
      }
      if (v.connections.length) {
        const end = (id: string) => (d.nodes.some((n) => n.id === id) ? nodeName(id) : elementLink(id));
        lines.push("", "## Connections", "", "| # | From | To | Description | Technology |", "|---|---|---|---|---|");
        for (const c of v.connections) lines.push(`| ${c.number} | ${end(c.from)} | ${end(c.to)} | ${cell(c.description)} | ${cell(c.technology)} |`);
      }
      lines.push("", `[All views and elements](../README.md)`, "");
      files.push({ path: `views/${v.id}.md`, content: lines.join("\n") });
      continue;
    }
    if (v.level === "event") {
      const laneName = (id: string | undefined) => cell(v.lanes.find((l) => l.id === id)?.name ?? id);
      const cardName = (id: string) => cell(v.cards.find((c) => c.id === id)?.name ?? id);
      if (v.lanes.length) {
        lines.push("", "## Lanes", "", "| Lane | Description |", "|---|---|");
        for (const lane of v.lanes) lines.push(`| ${cell(lane.name)} | ${cell(lane.description)} |`);
      }
      lines.push("", "## Cards", "");
      if (v.cards.length) {
        lines.push("| # | Card | Kind | Lane | Comes from | Description |", "|---|---|---|---|---|---|");
        for (const c of v.cards) lines.push(`| ${c.number} | ${cell(c.name)} | ${CARD_KIND_LABELS[c.kind]} | ${laneName(c.lane)} | ${c.from.map(cardName).join(", ")} | ${cell(c.description)} |`);
      } else lines.push("None yet.");
      lines.push("", `[All views and elements](../README.md)`, "");
      files.push({ path: `views/${v.id}.md`, content: lines.join("\n") });
      continue;
    }
    if (v.level === "wireframe") {
      const screenName = (id: string) => cell(v.screens.find((s) => s.id === id)?.name ?? id);
      /** A screen's widgets, numbered as 1, 2, then 2.1, 2.2 for what's in the second. */
      const rows = (widgets: Widget[], prefix: string): string[] =>
        widgets.flatMap((w) => {
          const number = `${prefix}${w.number}`;
          const text = cell((w.text ?? "").split(/\r?\n/).map((l) => l.trim()).filter(Boolean).join(" / "));
          return [`| ${number} | ${WIDGET_KIND_LABELS[w.kind]} | ${text} | ${w.to ? screenName(w.to) : ""} | ${cell(w.description)} |`, ...rows(w.widgets, `${number}.`)];
        });
      lines.push("", "## Screens");
      if (v.screens.length === 0) lines.push("", "None yet.");
      for (const s of v.screens) {
        lines.push("", `### ${s.number}. ${s.name}`, "", `${SCREEN_DEVICE_LABELS[s.device]} screen.${s.description ? ` ${s.description}` : ""}`, "");
        if (s.widgets.length) lines.push("| # | Widget | Text | Leads to | Description |", "|---|---|---|---|---|", ...rows(s.widgets, ""));
        else lines.push("Nothing on it yet.");
      }
      lines.push("", `[All views and elements](../README.md)`, "");
      files.push({ path: `views/${v.id}.md`, content: lines.join("\n") });
      continue;
    }
    if (v.level === "whiteboard") {
      const shapes = shapesInReadingOrder(v.shapes);
      /** An arrow's end as the table names it: its shape, and the side of it the end stays on, or its point. */
      const end = (e: Arrow["from"]) => {
        if (Array.isArray(e)) return `the point (${e[0]}, ${e[1]})`;
        const id = endShape(e)!;
        const s = v.shapes.find((x) => x.id === id);
        const side = endSide(e);
        return `${cell(s ? shapeName(s) : id)}${side ? ` (its ${side})` : ""}`;
      };
      lines.push("", "## Shapes", "");
      if (shapes.length) {
        lines.push("| Shape | Text |", "|---|---|");
        for (const s of shapes) lines.push(`| ${s.kind === "pen" ? "Pen line" : SHAPE_KIND_LABELS[s.kind]} | ${cell((s.text ?? "").split(/\r?\n/).map((l) => l.trim()).filter(Boolean).join(" / "))} |`);
      } else lines.push("None yet.");
      if (v.arrows.length) {
        lines.push("", "## Arrows", "", "| Arrow | From | To | Text |", "|---|---|---|---|");
        for (const a of v.arrows) lines.push(`| ${a.heads === "none" ? "Line" : a.heads === "both" ? "Arrow both ways" : "Arrow"} | ${end(a.from)} | ${end(a.to)} | ${cell(a.text)} |`);
      }
      const pens = v.shapes.filter((s) => s.kind === "pen").length;
      // Arrows to a shape that isn't there, or from one to itself, are left out too, but check says so.
      const offShape = (e: Arrow["from"]) => {
        const id = endShape(e);
        return id === undefined || v.shapes.find((s) => s.id === id)?.kind === "pen";
      };
      const loose = v.arrows.filter((a) => offShape(a.from) || offShape(a.to)).length;
      if (pens || loose) {
        const left = [pens ? `the ${pens === 1 ? "line" : `${pens} lines`} drawn with the pen` : "", loose ? `${loose === 1 ? "the arrow" : `${loose} arrows`} with an end at a point or on a pen's line` : ""].filter(Boolean);
        lines.push("", `The diagram above leaves out ${left.join(", and ")}, as Mermaid can't draw ${pens + loose === 1 ? "it" : "them"}. Open the view in the designer to see the whole whiteboard.`);
      }
      lines.push("", `[All views and elements](../README.md)`, "");
      files.push({ path: `views/${v.id}.md`, content: lines.join("\n") });
      continue;
    }
    if (v.level === "flowchart") {
      const text = (t: string | undefined) => cell((t ?? "").split(/\r?\n/).map((l) => l.trim()).filter(Boolean).join(" / "));
      const blockText = (id: string) => {
        const b = v.blocks.find((x) => x.id === id);
        return b ? text(b.text) : cell(id);
      };
      const laneName = (id: string | undefined) => cell(v.lanes.find((l) => l.id === id)?.name ?? id);
      // A lane for an element links to the element's page, when any lane is for one.
      const laneFor = (lane: Lane) => {
        const e = lane.element ? ws.elements.get(lane.element) : undefined;
        return e ? link(e, "views") : cell(lane.element);
      };
      if (v.lanes.some((l) => l.element)) {
        lines.push("", "## Lanes", "", "| Lane | Element | Description |", "|---|---|---|");
        for (const lane of v.lanes) lines.push(`| ${cell(lane.name)} | ${laneFor(lane)} | ${cell(lane.description)} |`);
      } else if (v.lanes.length) {
        lines.push("", "## Lanes", "", "| Lane | Description |", "|---|---|");
        for (const lane of v.lanes) lines.push(`| ${cell(lane.name)} | ${cell(lane.description)} |`);
      }
      lines.push("", "## Blocks", "");
      if (v.blocks.length && v.lanes.length) {
        lines.push("| # | Block | Kind | Lane | Description |", "|---|---|---|---|---|");
        for (const b of v.blocks) lines.push(`| ${b.number} | ${text(b.text)} | ${BLOCK_KIND_LABELS[b.kind]} | ${laneName(b.lane)} | ${cell(b.description)} |`);
      } else if (v.blocks.length) {
        lines.push("| # | Block | Kind | Description |", "|---|---|---|---|");
        for (const b of v.blocks) lines.push(`| ${b.number} | ${text(b.text)} | ${BLOCK_KIND_LABELS[b.kind]} | ${cell(b.description)} |`);
      } else lines.push("None yet.");
      if (v.flows.length) {
        lines.push("", "## Flows", "", "| # | From | To | Text |", "|---|---|---|---|");
        for (const f of v.flows) lines.push(`| ${f.number} | ${blockText(f.from)} | ${blockText(f.to)} | ${text(f.text)} |`);
      }
      lines.push("", `[All views and elements](../README.md)`, "");
      files.push({ path: `views/${v.id}.md`, content: lines.join("\n") });
      continue;
    }
    if (v.level === "entity") {
      const entityName = (id: string) => cell(v.entities.find((e) => e.id === id)?.name ?? id);
      lines.push("", "## Entities");
      if (v.entities.length === 0) lines.push("", "None yet.");
      for (const e of v.entities) {
        lines.push("", `### ${e.name.replace(/\s*\r?\n\s*/g, " ")}`);
        if (e.description) lines.push("", e.description);
        lines.push("");
        if (e.attributes.length) {
          lines.push("| Attribute | Type | Key | Description |", "|---|---|---|---|");
          for (const a of e.attributes) lines.push(`| ${cell(a.name)} | ${cell(a.type)} | ${a.keys.map((k) => k.toUpperCase()).join(", ")} | ${cell(a.description)} |`);
        } else lines.push("No attributes yet.");
      }
      if (v.links.length) {
        lines.push("", "## Links", "", "| # | From | To | How many | Text |", "|---|---|---|---|---|");
        for (const l of v.links) {
          const [from, to] = l.cardinality;
          lines.push(`| ${l.number} | ${entityName(l.from)} | ${entityName(l.to)} | ${CARDINALITY_LABELS[from]} to ${CARDINALITY_LABELS[to].toLowerCase()} | ${cell(l.text)} |`);
        }
      }
      lines.push("", `[All views and elements](../README.md)`, "");
      files.push({ path: `views/${v.id}.md`, content: lines.join("\n") });
      continue;
    }
    lines.push("", "## Elements", "");
    if (cv.nodes.length) {
      lines.push("| Element | Kind | Technology | Description |", "|---|---|---|---|");
      for (const n of cv.nodes) lines.push(`| ${link(n, "views")} | ${kindLabel(n)} | ${cell(n.technology)} | ${cell(n.description)} |`);
    } else {
      lines.push("None yet.");
    }
    if (cv.steps.length) {
      lines.push("", "## Steps", "", "| # | From | To | Description | Technology |", "|---|---|---|---|---|");
      for (const step of cv.steps) {
        const end = (id: string) => {
          const e = ws.elements.get(id);
          return e ? link(e, "views") : cell(id);
        };
        const description = step.reply ? `Reply${step.label ? `: ${cell(step.label)}` : ""}` : cell(step.label);
        lines.push(`| ${step.number} | ${end(step.from)} | ${end(step.to)} | ${description} | ${cell(step.labelTechnology)} |`);
      }
      // The notes of the relationships the steps go along, each once.
      const seen = new Set<string>();
      const sources = cv.steps.flatMap((step) => step.sources).filter(({ element, index }) => !seen.has(`${element}#${index}`) && seen.add(`${element}#${index}`));
      lines.push(...relNotes(ws, sources.map(({ element, index }) => ({ from: element, rel: ws.elements.get(element)!.uses[index]! }))));
    }
    if (cv.edges.length) {
      lines.push("", "## Relationships", "", "| From | To | Description | Technology |", "|---|---|---|---|");
      for (const e of cv.edges) {
        const from = ws.elements.get(e.from)!;
        const to = ws.elements.get(e.to)!;
        lines.push(`| ${link(from, "views")} | ${link(to, "views")} | ${described(e)} | ${cell(e.technology)} |`);
      }
      // Each arrow's relationships, which can be between elements inside its boxes.
      lines.push(...relNotes(ws, cv.edges.flatMap((e) => e.sources.map(({ element, index }) => ({ from: element, rel: ws.elements.get(element)!.uses[index]! })))));
    }
    lines.push("", `[All views and elements](../README.md)`, "");
    files.push({ path: `views/${v.id}.md`, content: lines.join("\n") });
  }

  // Elements
  for (const e of ws.elements.values()) {
    const d = describeElement(ws, e.id)!;
    const label = SHAPE_LABELS[e.shape].toLowerCase();
    const shape = e.shape === "box" ? undefined : `drawn as ${/^[aeiou]/.test(label) ? "an" : "a"} ${label}`;
    const stereotype = e.stereotype ? `«${e.stereotype}»` : undefined;
    const facts = [`**${kindLabel(e)}**`, stereotype, e.technology, shape, d.parent ? `inside ${link(d.parent, "elements")}` : undefined].filter(Boolean);
    const lines = [top, "", `# ${e.name}`, "", facts.join(" · ")];
    if (e.description) lines.push("", e.description);
    if (e.notes) lines.push("", e.notes);
    // In a code block, as members are code, with a fence longer than any run of backticks in them.
    if (e.members.length) {
      const fence = "`".repeat(Math.max(3, ...e.members.map((m) => Math.max(0, ...(m.match(/`+/g) ?? []).map((run) => run.length + 1)))));
      lines.push("", "## Members", "", `${fence}text`, ...e.members, fence);
    }
    if (d.children.length) {
      lines.push("", "## Contains", "", ...d.children.map((c) => `- ${link(c, "elements")} (${kindLabel(c).toLowerCase()})${c.description ? ` – ${c.description}` : ""}`));
    }
    if (d.libraries.length) {
      lines.push("", "## Libraries", "", ...d.libraries.map((l) => `- ${link(l, "elements")}${l.description ? ` – ${l.description}` : ""}`));
    }
    if (e.kind === "library") {
      lines.push("", "## Built into", "", ...(d.builtInto.length ? d.builtInto.map((c) => `- ${link(c, "elements")}`) : ["No container yet."]));
    }
    if (d.uses.length) {
      lines.push("", "## Uses", "", ...relTable(ws, d.uses.map(({ rel }) => ({ other: rel.to, rel }))), ...relNotes(ws, d.uses.map(({ rel }) => ({ from: e.id, rel }))));
    }
    if (d.usedBy.length) {
      lines.push("", "## Used by", "", ...relTable(ws, d.usedBy.map(({ from, rel }) => ({ other: from.id, rel }))), ...relNotes(ws, d.usedBy.map(({ from, rel }) => ({ from: from.id, rel }))));
    }
    const tags = tagEntries(e.tags);
    if (tags.length) lines.push("", "## Tags", "", "| Tag | Value |", "|---|---|", ...tags.map(([k, v]) => `| ${cell(k)} | ${cell(v)} |`));
    if (d.views.length) {
      const how = ({ as, runsIn, lanes }: (typeof d.views)[number]) =>
        as === "frame"
          ? " (as the frame)"
          : as === "states"
            ? " (its states)"
            : as === "screens"
              ? " (its screens)"
              : as === "process"
                ? ` (its process${lanes ? `, and its lane${lanes.length === 1 ? "" : "s"}, ${lanes.map((l) => l.name).join(", ")}` : ""})`
                : as === "data"
                  ? " (its data)"
                  : as === "deployed"
                    ? ` (runs in ${runsIn!.map((n) => n.name).join(", ")})`
                    : as === "lane"
                      ? ` (its lane${lanes!.length === 1 ? "" : "s"}, ${lanes!.map((l) => l.name).join(", ")})`
                      : "";
      lines.push("", "## Shown in", "", ...d.views.map((shown) => `- [${shown.view.title}](../views/${shown.view.id}.md)${how(shown)}`));
    }
    lines.push("", `[All views and elements](../README.md)`, "");
    files.push({ path: `elements/${e.id}.md`, content: lines.join("\n") });
  }
  return files;
}
