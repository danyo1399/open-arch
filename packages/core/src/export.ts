/**
 * Human-readable docs generated from a workspace: an index, one page per
 * element and one per view with its Mermaid diagram. They're output only:
 * every page says so, and tools rewrite them freely.
 */
import { renderMermaid } from "./mermaid.js";
import { kindLabel, tagEntries, tagText } from "./model.js";
import { computeAllViews, describeElement, modelTree, type TreeNode } from "./query.js";
import type { ArchElement, Relationship } from "./types.js";
import type { Workspace } from "./workspace.js";

export interface ExportedFile {
  /** Relative to the docs folder, with `/` separators. */
  path: string;
  content: string;
}

/** Every generated page starts with this, which is how tools know they may overwrite or delete it. */
export const GENERATED_MARKER = "<!-- Generated by open-arch";

function banner(source: string): string {
  return `${GENERATED_MARKER} from ${source}. Don't edit: change the model in the designer or with the open-arch CLI, and this page is rewritten. -->`;
}

/** Text safe inside a markdown table cell. */
function cell(text: string | undefined): string {
  return (text ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function link(e: ArchElement, from: "root" | "elements" | "views"): string {
  const href = from === "elements" ? `${e.id}.md` : from === "views" ? `../elements/${e.id}.md` : `elements/${e.id}.md`;
  return `[${e.name}](${href})`;
}

/** Relationships to or from an element, with a Tags column when any of them has tags. */
function relTable(ws: Workspace, rows: { other: string; rel: Relationship }[]): string[] {
  const tagged = rows.some(({ rel }) => Object.keys(rel.tags).length > 0);
  const head = tagged ? ["| Element | Description | Technology | Tags |", "|---|---|---|---|"] : ["| Element | Description | Technology |", "|---|---|---|"];
  return [
    ...head,
    ...rows.map(({ other, rel }) => {
      const target = ws.elements.get(other);
      return `| ${target ? link(target, "elements") : cell(other)} | ${cell(rel.description)} | ${cell(rel.technology)} |${tagged ? ` ${cell(tagText(rel.tags))} |` : ""}`;
    }),
  ];
}

/**
 * The notes of these relationships, for under the table that lists them: each under a
 * heading that names it, as the table's rows can't hold markdown. Those without notes are left out.
 */
function relNotes(ws: Workspace, rows: { from: string; rel: Relationship }[]): string[] {
  const name = (id: string) => ws.elements.get(id)?.name ?? id;
  return rows.flatMap(({ from, rel }) => {
    if (!rel.notes) return [];
    const description = rel.description ? `: ${rel.description.replace(/\s*\r?\n\s*/g, " ")}` : "";
    return ["", `### ${name(from)} → ${name(rel.to)}${description}`, "", rel.notes];
  });
}

/**
 * The docs for a workspace. `source` names the .openarch file in the banner.
 * Paths: README.md, elements/<id>.md, views/<id>.md.
 */
export function exportDocs(ws: Workspace, source: string): ExportedFile[] {
  const top = banner(source);
  const views = computeAllViews(ws);
  const files: ExportedFile[] = [];

  // Index
  const tree: string[] = [];
  const walk = (node: TreeNode, depth: number) => {
    const e = node.element;
    tree.push(`${"  ".repeat(depth)}- ${link(e, "root")} (${kindLabel(e).toLowerCase()}${e.technology ? `, ${e.technology}` : ""})${e.description ? ` – ${e.description}` : ""}`);
    node.children.forEach((c) => walk(c, depth + 1));
  };
  modelTree(ws).forEach((n) => walk(n, 0));
  files.push({
    path: "README.md",
    content: [
      top,
      "",
      `# ${ws.doc.name}`,
      ...(ws.doc.description ? ["", ws.doc.description] : []),
      "",
      "## Views",
      "",
      ...(views.length ? views.map((cv) => `- [${cv.view.title}](views/${cv.view.id}.md)${cv.view.description ? ` – ${cv.view.description}` : ""}`) : ["No views yet."]),
      "",
      "## Model",
      "",
      ...(tree.length ? tree : ["No elements yet."]),
      "",
    ].join("\n"),
  });

  // Views
  for (const cv of views) {
    const v = cv.view;
    const scope = v.scope ? ws.elements.get(v.scope) : undefined;
    const lines = [top, "", `# ${v.title}`, "", `${v.level[0]!.toUpperCase()}${v.level.slice(1)} view${scope ? ` of ${link(scope, "views")}` : ""}.`];
    if (v.description) lines.push("", v.description);
    if (v.notes) lines.push("", v.notes);
    lines.push("", "```mermaid", renderMermaid(cv), "```");
    // The diagram's sticky notes, as quotes in reading order.
    if (v.stickies.length) lines.push("", "## Sticky notes", ...v.stickies.flatMap((s) => ["", ...s.text.split(/\r?\n/).map((l) => `> ${l}`.trimEnd())]));
    lines.push("", "## Elements", "");
    if (cv.nodes.length) {
      lines.push("| Element | Kind | Technology | Description |", "|---|---|---|---|");
      for (const n of cv.nodes) lines.push(`| ${link(n, "views")} | ${kindLabel(n)} | ${cell(n.technology)} | ${cell(n.description)} |`);
    } else {
      lines.push("None yet.");
    }
    if (cv.steps.length) {
      lines.push("", "## Steps", "", "| # | From | To | Description | Technology |", "|---|---|---|---|---|");
      for (const step of cv.steps) {
        const end = (id: string) => {
          const e = ws.elements.get(id);
          return e ? link(e, "views") : cell(id);
        };
        const description = step.reply ? `Reply${step.label ? `: ${cell(step.label)}` : ""}` : cell(step.label);
        lines.push(`| ${step.number} | ${end(step.from)} | ${end(step.to)} | ${description} | ${cell(step.labelTechnology)} |`);
      }
      // The notes of the relationships the steps go along, each once.
      const seen = new Set<string>();
      const sources = cv.steps.flatMap((step) => step.sources).filter(({ element, index }) => !seen.has(`${element}#${index}`) && seen.add(`${element}#${index}`));
      lines.push(...relNotes(ws, sources.map(({ element, index }) => ({ from: element, rel: ws.elements.get(element)!.uses[index]! }))));
    }
    if (cv.edges.length) {
      lines.push("", "## Relationships", "", "| From | To | Description | Technology |", "|---|---|---|---|");
      for (const e of cv.edges) {
        const from = ws.elements.get(e.from)!;
        const to = ws.elements.get(e.to)!;
        lines.push(`| ${link(from, "views")} | ${link(to, "views")} | ${cell(e.description)} | ${cell(e.technology)} |`);
      }
      // Each arrow's relationships, which can be between elements inside its boxes.
      lines.push(...relNotes(ws, cv.edges.flatMap((e) => e.sources.map(({ element, index }) => ({ from: element, rel: ws.elements.get(element)!.uses[index]! })))));
    }
    lines.push("", `[All views and elements](../README.md)`, "");
    files.push({ path: `views/${v.id}.md`, content: lines.join("\n") });
  }

  // Elements
  for (const e of ws.elements.values()) {
    const d = describeElement(ws, e.id)!;
    const shape = e.shape === "box" ? undefined : `drawn as a ${e.shape.replace("-", " ")}`;
    const facts = [`**${kindLabel(e)}**`, e.technology, shape, d.parent ? `inside ${link(d.parent, "elements")}` : undefined].filter(Boolean);
    const lines = [top, "", `# ${e.name}`, "", facts.join(" · ")];
    if (e.description) lines.push("", e.description);
    if (e.notes) lines.push("", e.notes);
    if (d.children.length) {
      lines.push("", "## Contains", "", ...d.children.map((c) => `- ${link(c, "elements")} (${kindLabel(c).toLowerCase()})${c.description ? ` – ${c.description}` : ""}`));
    }
    if (d.uses.length) {
      lines.push("", "## Uses", "", ...relTable(ws, d.uses.map(({ rel }) => ({ other: rel.to, rel }))), ...relNotes(ws, d.uses.map(({ rel }) => ({ from: e.id, rel }))));
    }
    if (d.usedBy.length) {
      lines.push("", "## Used by", "", ...relTable(ws, d.usedBy.map(({ from, rel }) => ({ other: from.id, rel }))), ...relNotes(ws, d.usedBy.map(({ from, rel }) => ({ from: from.id, rel }))));
    }
    const tags = tagEntries(e.tags);
    if (tags.length) lines.push("", "## Tags", "", "| Tag | Value |", "|---|---|", ...tags.map(([k, v]) => `| ${cell(k)} | ${cell(v)} |`));
    if (d.views.length) {
      lines.push("", "## Shown in", "", ...d.views.map(({ view, as }) => `- [${view.title}](../views/${view.id}.md)${as === "frame" ? " (as the frame)" : ""}`));
    }
    lines.push("", `[All views and elements](../README.md)`, "");
    files.push({ path: `elements/${e.id}.md`, content: lines.join("\n") });
  }
  return files;
}
